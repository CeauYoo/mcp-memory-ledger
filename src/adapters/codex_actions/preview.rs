//! Pure candidate generation. This module never reads or writes host files, installs
//! hooks, changes trust, or grants permissions. Hashes detect changes; they do not
//! authenticate a manifest. Callers must separately verify host and binary evidence.
use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};
use sha2::{Digest, Sha256};

const MAX_CONFIG_BYTES: usize = 4 * 1024 * 1024;
const MAX_COMMAND_BYTES: usize = 64 * 1024;

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum PreviewPlatform {
    Posix,
    Windows,
    Unknown,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct PreviewMetadata {
    /// Opt-in severe profile: unclassified local tools will be denied.
    pub strict_local: bool,
    pub target_file: String,
    pub binary_path: Option<String>,
    pub binary_sha256: Option<String>,
    pub policy_revision: Option<u64>,
    pub policy_digest: Option<String>,
    pub host_version: Option<String>,
    /// Caller-supplied observations, never interpreted as proof of protection.
    pub probe_evidence: Vec<String>,
    pub platform: PreviewPlatform,
}

impl Default for PreviewMetadata {
    fn default() -> Self {
        Self {
            strict_local: false,
            target_file: String::new(),
            binary_path: None,
            binary_sha256: None,
            policy_revision: None,
            policy_digest: None,
            host_version: None,
            probe_evidence: Vec::new(),
            platform: if cfg!(windows) {
                PreviewPlatform::Windows
            } else if cfg!(unix) {
                PreviewPlatform::Posix
            } else {
                PreviewPlatform::Unknown
            },
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PreviewManifest {
    pub schema_version: u32,
    pub metadata: PreviewMetadata,
    pub before_sha256: String,
    pub after_sha256: String,
    /// Exact original bytes, including whitespace, for lossless rollback.
    pub source_snapshot: Vec<u8>,
    /// Exact proposed bytes permit independent hash and three-way comparison.
    pub candidate_snapshot: Vec<u8>,
    pub changed: bool,
    pub status: String,
    pub host_status: String,
    pub coverage: Vec<String>,
    pub unknowns_and_limits: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PreviewBundle {
    pub before_bytes: Vec<u8>,
    pub after_bytes: Vec<u8>,
    pub manifest: PreviewManifest,
    /// A structural diff. Re-serialization can change whitespace/key ordering.
    pub diff: String,
    pub rollback_plan: RestorePlan,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(tag = "status", rename_all = "snake_case")]
pub enum RestorePlan {
    /// The I/O owner must recheck this hash immediately before any replacement.
    Restore {
        expected_current_sha256: String,
        restore_sha256: String,
        restore_bytes: Vec<u8>,
        host_trust_recheck_required: bool,
    },
    AlreadyOriginal {
        current_sha256: String,
    },
    /// Do not overwrite. Present base/applied/current for a human merge instead.
    Conflict {
        expected_applied_sha256: String,
        actual_sha256: String,
        original_sha256: String,
        three_way_review_required: bool,
    },
    InvalidManifest {
        reason: String,
    },
}

pub fn sha256(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}

/// Merge one generated, exact PreToolUse command into a JSON hooks configuration.
/// `command` must be generated by the trusted caller from its verified absolute
/// binary path; this function does not execute or authenticate a shell command.
/// Existing entries are retained as JSON values; an exact existing matcher and
/// command handler makes the preview byte-for-byte idempotent. Unknown object fields
/// are retained. Duplicate JSON keys are rejected rather than silently discarded.
/// Floating-point numbers are rejected to avoid rounding unrelated settings.
/// Empty bytes are not a valid config; use `{}` for a new candidate file.
/// A newly absent file needs separate create/delete planning by the I/O owner.
pub fn build_preview(
    existing: &[u8],
    command: &str,
    metadata: PreviewMetadata,
) -> Result<PreviewBundle> {
    match metadata.platform {
        PreviewPlatform::Windows => bail!("Windows command preview unsupported; host unverified"),
        PreviewPlatform::Unknown => bail!("command preview unsupported on unknown platform"),
        PreviewPlatform::Posix => {}
    }
    if existing.len() > MAX_CONFIG_BYTES {
        bail!("hooks configuration exceeds preview size limit");
    }
    if command.trim().is_empty()
        || command.len() > MAX_COMMAND_BYTES
        || command.chars().any(char::is_control)
    {
        bail!("generated command must be nonempty, bounded, and contain no control characters");
    }
    if let Some(path) = &metadata.binary_path
        && (!path.starts_with('/') || path.chars().any(char::is_control))
    {
        bail!("binary_path must be an absolute POSIX path without control characters");
    }
    let StrictValue(mut root) = serde_json::from_slice(existing)
        .context("expected valid JSON hooks configuration without duplicate keys")?;
    let object = root
        .as_object_mut()
        .context("hooks configuration must be an object")?;
    let hooks = object.entry("hooks").or_insert_with(|| json!({}));
    let hooks = hooks.as_object_mut().context("hooks must be an object")?;
    let entries = hooks.entry("PreToolUse").or_insert_with(|| json!([]));
    let entries = entries
        .as_array_mut()
        .context("hooks.PreToolUse must be an array")?;
    // Default is patch-only. Broader interception is an explicit severe profile;
    // it denies unclassified local tools rather than pretending to inspect shell.
    let matcher = if metadata.strict_local {
        ".*"
    } else {
        "^apply_patch$"
    };
    let handler = json!({"type": "command", "command": command, "timeout": 15});
    let already_present = entries.iter().any(|entry| {
        let Some(group) = entry.as_object() else {
            return false;
        };
        group.get("matcher").is_some_and(|v| v == matcher)
            && group.keys().all(|k| k == "matcher" || k == "hooks")
            && group
                .get("hooks")
                .and_then(Value::as_array)
                .is_some_and(|commands| commands.iter().any(|hook| hook == &handler))
    });
    let fragment = json!({"matcher": matcher, "hooks": [handler]});
    if !already_present {
        entries.push(fragment.clone());
    }
    let after_bytes = if already_present {
        existing.to_vec()
    } else {
        let mut bytes = serde_json::to_vec_pretty(&root)?;
        bytes.push(b'\n');
        bytes
    };
    let coverage = if metadata.strict_local {
        vec!["Proposed strict-local PreToolUse matcher .*; unclassified local tools are denied, not semantically checked".into()]
    } else {
        vec!["Proposed patch-only PreToolUse matcher ^apply_patch$; shell and other tools remain uncovered".into()]
    };
    let manifest = PreviewManifest {
        schema_version: 1,
        metadata,
        before_sha256: sha256(existing),
        after_sha256: sha256(&after_bytes),
        source_snapshot: existing.to_vec(),
        candidate_snapshot: after_bytes.clone(),
        changed: !already_present,
        status: "preview_only_not_installed".into(),
        host_status: "unverified".into(),
        coverage,
        unknowns_and_limits: vec![
            "Not a sandbox, execution authorization, or fail-closed guarantee".into(),
            "Native sandbox, permission, network and deny-rule values are unchanged".into(),
            "Host version, hook execution, trust and binary identity require independent verification".into(),
            "Target ownership, permissions and non-synchronized storage are unverified; no automatic installation".into(),
            "No observed host coverage; in both profiles hosted tools, running processes/write_stdin and host bypass paths are not protected".into(),
            "Patch-only does not intercept shell; strict-local explicitly denies unclassified local tools and can disrupt workflows".into(),
            "Windows command preview is unsupported".into(),
            "SHA-256 provides integrity comparison, not authenticity".into(),
            "Rollback restores adapter configuration only, not completed effects or task data; host trust must be rechecked".into(),
            "Existing JSON values are retained; whitespace and key ordering may change in the candidate".into(),
        ],
    };
    let rollback_plan = plan_restore(&after_bytes, &manifest);
    let diff = if already_present {
        "No change: exact PreToolUse matcher and command handler already present.\n".into()
    } else {
        format!(
            "Append /hooks/PreToolUse/- (create missing containers):\n+ {}\nAll other JSON values unchanged; candidate formatting may differ.\n",
            serde_json::to_string(&fragment)?
        )
    };
    Ok(PreviewBundle {
        before_bytes: existing.to_vec(),
        after_bytes,
        manifest,
        diff,
        rollback_plan,
    })
}

/// Plan only: no host access, replacement, trust changes, or permission changes.
/// The returned expected hash is a CAS precondition, not a lock. I/O must back up
/// file permissions, reject changed paths/symlinks, recheck the precondition, and
/// journal/verify its actual replacement. Multiple files are not atomic here.
pub fn plan_restore(current: &[u8], manifest: &PreviewManifest) -> RestorePlan {
    if manifest.schema_version != 1
        || sha256(&manifest.source_snapshot) != manifest.before_sha256
        || sha256(&manifest.candidate_snapshot) != manifest.after_sha256
        || manifest.changed != (manifest.before_sha256 != manifest.after_sha256)
    {
        return RestorePlan::InvalidManifest {
            reason: "Unsupported schema or inconsistent snapshot/hash/change flag".into(),
        };
    }
    let current_sha256 = sha256(current);
    if current_sha256 == manifest.before_sha256 {
        return RestorePlan::AlreadyOriginal { current_sha256 };
    }
    if current_sha256 != manifest.after_sha256 {
        return RestorePlan::Conflict {
            expected_applied_sha256: manifest.after_sha256.clone(),
            actual_sha256: current_sha256,
            original_sha256: manifest.before_sha256.clone(),
            three_way_review_required: true,
        };
    }
    RestorePlan::Restore {
        expected_current_sha256: current_sha256,
        restore_sha256: manifest.before_sha256.clone(),
        restore_bytes: manifest.source_snapshot.clone(),
        host_trust_recheck_required: true,
    }
}

// serde_json::Value normally keeps only the last occurrence of duplicate keys.
// Use a recursive visitor so preview cannot silently remove unrelated settings.
struct StrictValue(Value);
impl<'de> Deserialize<'de> for StrictValue {
    fn deserialize<D: serde::Deserializer<'de>>(
        deserializer: D,
    ) -> std::result::Result<Self, D::Error> {
        struct Visitor;
        impl<'de> serde::de::Visitor<'de> for Visitor {
            type Value = StrictValue;
            fn expecting(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                f.write_str("JSON without duplicate object keys")
            }
            fn visit_bool<E: serde::de::Error>(
                self,
                v: bool,
            ) -> std::result::Result<StrictValue, E> {
                Ok(StrictValue(v.into()))
            }
            fn visit_i64<E: serde::de::Error>(self, v: i64) -> std::result::Result<StrictValue, E> {
                Ok(StrictValue(v.into()))
            }
            fn visit_u64<E: serde::de::Error>(self, v: u64) -> std::result::Result<StrictValue, E> {
                Ok(StrictValue(v.into()))
            }
            fn visit_f64<E: serde::de::Error>(
                self,
                _v: f64,
            ) -> std::result::Result<StrictValue, E> {
                // Without arbitrary_precision support, round-tripping a float may
                // alter unrelated configuration. Refuse rather than silently round.
                Err(E::custom(
                    "floating-point JSON numbers unsupported for lossless configuration preview",
                ))
            }
            fn visit_str<E: serde::de::Error>(
                self,
                v: &str,
            ) -> std::result::Result<StrictValue, E> {
                Ok(StrictValue(v.into()))
            }
            fn visit_string<E: serde::de::Error>(
                self,
                v: String,
            ) -> std::result::Result<StrictValue, E> {
                Ok(StrictValue(v.into()))
            }
            fn visit_unit<E: serde::de::Error>(self) -> std::result::Result<StrictValue, E> {
                Ok(StrictValue(Value::Null))
            }
            fn visit_none<E: serde::de::Error>(self) -> std::result::Result<StrictValue, E> {
                Ok(StrictValue(Value::Null))
            }
            fn visit_seq<A: serde::de::SeqAccess<'de>>(
                self,
                mut seq: A,
            ) -> std::result::Result<StrictValue, A::Error> {
                let mut values = Vec::new();
                while let Some(StrictValue(value)) = seq.next_element()? {
                    values.push(value);
                }
                Ok(StrictValue(Value::Array(values)))
            }
            fn visit_map<A: serde::de::MapAccess<'de>>(
                self,
                mut map: A,
            ) -> std::result::Result<StrictValue, A::Error> {
                let mut values = serde_json::Map::new();
                while let Some(key) = map.next_key::<String>()? {
                    if values.contains_key(&key) {
                        return Err(serde::de::Error::custom("duplicate JSON object key"));
                    }
                    let StrictValue(value) = map.next_value()?;
                    values.insert(key, value);
                }
                Ok(StrictValue(Value::Object(values)))
            }
        }
        deserializer.deserialize_any(Visitor)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    fn preview(bytes: &[u8]) -> PreviewBundle {
        build_preview(
            bytes,
            "'/opt/ledger/bin/ledger' codex-actions check",
            PreviewMetadata {
                platform: PreviewPlatform::Posix,
                ..Default::default()
            },
        )
        .unwrap()
    }
    #[test]
    fn default_is_patch_only_with_bounded_timeout() {
        let bundle = preview(b"{}");
        let candidate: Value = serde_json::from_slice(&bundle.after_bytes).unwrap();
        assert_eq!(
            candidate["hooks"]["PreToolUse"][0]["matcher"],
            "^apply_patch$"
        );
        assert_eq!(
            candidate["hooks"]["PreToolUse"][0]["hooks"][0]["timeout"],
            15
        );
    }
    #[test]
    fn strict_profile_is_explicit_and_not_confused_with_patch_hook() {
        let patch = preview(b"{}");
        let command = "'/opt/ledger/bin/ledger' codex-actions check";
        let strict = build_preview(
            &patch.after_bytes,
            command,
            PreviewMetadata {
                strict_local: true,
                platform: PreviewPlatform::Posix,
                ..Default::default()
            },
        )
        .unwrap();
        let candidate: Value = serde_json::from_slice(&strict.after_bytes).unwrap();
        assert_eq!(
            candidate["hooks"]["PreToolUse"].as_array().unwrap().len(),
            2
        );
        assert_eq!(candidate["hooks"]["PreToolUse"][1]["matcher"], ".*");
        assert!(strict.manifest.changed);
        let repeat = build_preview(
            &strict.after_bytes,
            command,
            PreviewMetadata {
                strict_local: true,
                platform: PreviewPlatform::Posix,
                ..Default::default()
            },
        )
        .unwrap();
        assert!(!repeat.manifest.changed);
    }
    #[test]
    fn differing_handler_timeout_is_not_exact_duplicate() {
        let first = preview(b"{}");
        let mut changed: Value = serde_json::from_slice(&first.after_bytes).unwrap();
        changed["hooks"]["PreToolUse"][0]["hooks"][0]["timeout"] = json!(1);
        let next = preview(&serde_json::to_vec(&changed).unwrap());
        assert!(next.manifest.changed);
    }
    #[test]
    fn preserves_existing_hooks_and_native_permissions() {
        let before = br#"{"sandbox_mode":"read-only","permissions":{"network":false},"hooks":{"Stop":[{"unknown":42}],"PreToolUse":[{"matcher":"Bash","hooks":[{"type":"command","command":"other"}]}]},"custom":{"x":[1,true,null]}}"#;
        let bundle = preview(before);
        assert_eq!(bundle.before_bytes, before);
        let mut after: Value = serde_json::from_slice(&bundle.after_bytes).unwrap();
        after["hooks"]["PreToolUse"].as_array_mut().unwrap().pop();
        assert_eq!(after, serde_json::from_slice::<Value>(before).unwrap());
        assert_eq!(bundle.manifest.host_status, "unverified");
        assert_eq!(bundle.manifest.status, "preview_only_not_installed");
    }
    #[test]
    fn repeat_is_byte_identical() {
        let first = preview(b"{ }");
        let second = preview(&first.after_bytes);
        assert_eq!(first.after_bytes, second.after_bytes);
        assert!(!second.manifest.changed);
        assert!(matches!(
            second.rollback_plan,
            RestorePlan::AlreadyOriginal { .. }
        ));
    }
    #[test]
    fn exact_restore_and_edit_conflict() {
        let original = b"{ \n  \"hooks\": {} }\n";
        let bundle = preview(original);
        match plan_restore(&bundle.after_bytes, &bundle.manifest) {
            RestorePlan::Restore { restore_bytes, .. } => assert_eq!(restore_bytes, original),
            other => panic!("unexpected: {other:?}"),
        }
        assert!(matches!(
            plan_restore(b"{\"user_edit\":true}", &bundle.manifest),
            RestorePlan::Conflict { .. }
        ));
        assert!(matches!(
            plan_restore(original, &bundle.manifest),
            RestorePlan::AlreadyOriginal { .. }
        ));
    }
    #[test]
    fn corrupt_manifest_is_not_restored() {
        let mut bundle = preview(b"{}");
        bundle.manifest.source_snapshot.push(b' ');
        assert!(matches!(
            plan_restore(&bundle.after_bytes, &bundle.manifest),
            RestorePlan::InvalidManifest { .. }
        ));
    }
    #[test]
    fn malformed_and_duplicate_configs_are_rejected() {
        for bytes in [
            b"[]".as_slice(),
            b"",
            b"null",
            br#"{"hooks":[]}"#,
            br#"{"hooks":{"PreToolUse":{}}}"#,
            br#"{"a":1,"a":2}"#,
            br#"{"nested":{"a":1,"a":2}}"#,
            br#"{"custom":0.1234567890123456789}"#,
        ] {
            assert!(build_preview(bytes, "/opt/ledger check", PreviewMetadata::default()).is_err());
        }
    }
    #[test]
    fn windows_and_unknown_platforms_are_unsupported() {
        for platform in [PreviewPlatform::Windows, PreviewPlatform::Unknown] {
            assert!(
                build_preview(
                    b"{}",
                    "C:\\ledger.exe check",
                    PreviewMetadata {
                        platform,
                        ..Default::default()
                    }
                )
                .is_err()
            );
        }
    }
    #[test]
    fn rejects_empty_or_multiline_commands_and_relative_binary() {
        for command in ["", "  ", "/bin/ledger\ncheck", "/bin/ledger\0check"] {
            assert!(build_preview(b"{}", command, PreviewMetadata::default()).is_err());
        }
        assert!(
            build_preview(
                b"{}",
                "ledger check",
                PreviewMetadata {
                    binary_path: Some("ledger".into()),
                    ..Default::default()
                }
            )
            .is_err()
        );
    }
}
