//! Schema 10 authority. Only explicit migration installs this table. No read repairs it.
use super::SqliteStore;
use crate::{domain::recall_applicability::*, error::AppError};
use sqlx::{Row, SqliteConnection};
pub(super) async fn install(conn: &mut SqliteConnection) -> Result<(), AppError> {
    sqlx::query("CREATE TABLE recall_applicability (namespace TEXT NOT NULL, reference TEXT NOT NULL, revision INTEGER NOT NULL CHECK(revision>0), request_id TEXT NOT NULL, request_json TEXT NOT NULL, payload_json TEXT NOT NULL, PRIMARY KEY(namespace,reference,revision), UNIQUE(namespace,request_id))").execute(conn).await.map_err(db)?;
    Ok(())
}
fn db(_: sqlx::Error) -> AppError {
    AppError::Message(
        "recall applicability authority database error; explicit inspection required".into(),
    )
}
fn corrupt() -> AppError {
    AppError::Message(
        "recall applicability authority corruption; explicit inspection required".into(),
    )
}
/// Preflight types, lengths and total budget in the same transaction before JSON materialization.
async fn read(
    conn: &mut SqliteConnection,
    namespace: &str,
    reference: Option<&str>,
    request_id: Option<&str>,
) -> Result<Option<(String, RecallApplicabilityRevision)>, AppError> {
    let where_clause = if reference.is_some() {
        "namespace=? AND reference=? ORDER BY revision DESC LIMIT 1"
    } else {
        "namespace=? AND request_id=? LIMIT 1"
    };
    let id = reference.or(request_id).ok_or_else(corrupt)?;
    let sql = format!(
        "SELECT revision, typeof(request_json) AS rt, typeof(payload_json) AS pt, length(CAST(request_json AS BLOB)) AS rn, length(CAST(payload_json AS BLOB)) AS pn, typeof(request_id) AS it, length(CAST(request_id AS BLOB)) AS il, typeof(reference) AS ft, length(CAST(reference AS BLOB)) AS fl FROM recall_applicability WHERE {where_clause}"
    );
    let Some(meta) = sqlx::query(&sql)
        .bind(namespace)
        .bind(id)
        .fetch_optional(&mut *conn)
        .await
        .map_err(db)?
    else {
        return Ok(None);
    };
    if meta.try_get::<&str, _>("it").map_err(|_| corrupt())? != "text"
        || meta.try_get::<&str, _>("ft").map_err(|_| corrupt())? != "text"
        || !(1..=128).contains(&meta.try_get::<i64, _>("il").map_err(|_| corrupt())?)
        || !(1..=256).contains(&meta.try_get::<i64, _>("fl").map_err(|_| corrupt())?)
    {
        return Err(corrupt());
    }
    let revision: i64 = meta.try_get("revision").map_err(|_| corrupt())?;
    let rn: i64 = meta.try_get("rn").map_err(|_| corrupt())?;
    let pn: i64 = meta.try_get("pn").map_err(|_| corrupt())?;
    if revision <= 0
        || meta.try_get::<&str, _>("rt").map_err(|_| corrupt())? != "text"
        || meta.try_get::<&str, _>("pt").map_err(|_| corrupt())? != "text"
        || rn < 0
        || pn < 0
        || rn > 20000
        || pn > MAX_METADATA_BYTES as i64
        || rn + pn > 36384
    {
        return Err(corrupt());
    }
    let sql = format!(
        "SELECT request_id,reference,request_json,payload_json FROM recall_applicability WHERE {where_clause}"
    );
    let row = sqlx::query(&sql)
        .bind(namespace)
        .bind(id)
        .fetch_one(&mut *conn)
        .await
        .map_err(db)?;
    let request: String = row.try_get("request_json").map_err(|_| corrupt())?;
    let declaration: RecallApplicability = serde_json::from_str(
        row.try_get::<&str, _>("payload_json")
            .map_err(|_| corrupt())?,
    )
    .map_err(|_| corrupt())?;
    declaration.validate().map_err(|_| corrupt())?;
    let original: DeclareRecallApplicabilityRequest =
        serde_json::from_str(&request).map_err(|_| corrupt())?;
    if row
        .try_get::<&str, _>("request_id")
        .map_err(|_| corrupt())?
        != original.request_id
        || row.try_get::<&str, _>("reference").map_err(|_| corrupt())? != declaration.reference
        || original.declaration != declaration
        || declaration.namespace != namespace
        || reference.is_some_and(|r| r != declaration.reference)
        || request_id.is_some_and(|r| r != original.request_id)
        || original.expected_revision.checked_add(1) != Some(revision as u64)
    {
        return Err(corrupt());
    }
    Ok(Some((
        request,
        RecallApplicabilityRevision {
            revision: revision as u64,
            declaration,
        },
    )))
}
pub(super) async fn load(
    conn: &mut SqliteConnection,
    namespace: &str,
    reference: &str,
) -> Result<Option<RecallApplicability>, AppError> {
    Ok(read(conn, namespace, Some(reference), None)
        .await?
        .map(|(_, r)| r.declaration))
}
impl SqliteStore {
    /// Explicit caller declaration; not generated by host context or a model.
    pub async fn declare_recall_applicability(
        &self,
        request: DeclareRecallApplicabilityRequest,
    ) -> Result<RecallApplicabilityRevision, AppError> {
        request.declaration.validate()?;
        if request.request_id.is_empty()
            || request.request_id.len() > 128
            || request.request_id.contains('\0')
            || request.expected_revision >= i64::MAX as u64
        {
            return Err(AppError::InvalidParams(
                "invalid applicability request id/revision".into(),
            ));
        }
        let encoded = serde_json::to_string(&request).map_err(|_| corrupt())?;
        if encoded.len() > 20000 {
            return Err(AppError::InvalidParams(
                "applicability request budget exceeded".into(),
            ));
        }
        let mut tx = self.pool.begin_with("BEGIN IMMEDIATE").await.map_err(db)?;
        let d = &request.declaration;
        if let Some((previous, result)) =
            read(&mut tx, &d.namespace, None, Some(&request.request_id)).await?
        {
            if previous != encoded {
                return Err(AppError::InvalidParams(
                    "applicability request id conflict".into(),
                ));
            }
            tx.rollback().await.map_err(db)?;
            return Ok(result);
        }
        let current = read(&mut tx, &d.namespace, Some(&d.reference), None)
            .await?
            .map(|(_, r)| r.revision)
            .unwrap_or(0);
        if current != request.expected_revision {
            return Err(AppError::InvalidParams(
                "applicability revision conflict".into(),
            ));
        }
        let (table, column, id) = if let Some(id) = d.reference.strip_prefix("claim:") {
            ("claims", "claim_id", id)
        } else {
            (
                "events",
                "event_id",
                d.reference.strip_prefix("event:").ok_or_else(corrupt)?,
            )
        };
        let owner = crate::domain::types::Namespace::parse(d.namespace.clone())
            .map_err(|_| corrupt())?
            .derived_owner();
        let owner = match owner {
            crate::domain::types::Owner::Self_ => "self",
            crate::domain::types::Owner::User => "user",
            crate::domain::types::Owner::World => "world",
            crate::domain::types::Owner::Unknown => "unknown",
        };
        let sql =
            format!("SELECT count(*) FROM {table} WHERE namespace=? AND {column}=? AND owner=?");
        let exists: i64 = sqlx::query_scalar(&sql)
            .bind(&d.namespace)
            .bind(id)
            .bind(owner)
            .fetch_one(&mut *tx)
            .await
            .map_err(db)?;
        if exists != 1 {
            return Err(AppError::InvalidParams(
                "applicability target not found in namespace".into(),
            ));
        }
        let revision = current + 1;
        sqlx::query("INSERT INTO recall_applicability(namespace,reference,revision,request_id,request_json,payload_json) VALUES(?,?,?,?,?,?)").bind(&d.namespace).bind(&d.reference).bind(revision as i64).bind(&request.request_id).bind(encoded).bind(serde_json::to_string(d).map_err(|_|corrupt())?).execute(&mut *tx).await.map_err(db)?;
        let result = read(&mut tx, &d.namespace, Some(&d.reference), None)
            .await?
            .ok_or_else(corrupt)?
            .1;
        tx.commit().await.map_err(db)?;
        Ok(result)
    }
}
