export function chooseLocale(saved, languages = []) {
  if (Object.hasOwn(messages, saved)) return saved;
  for (const language of languages) {
    const prefix = language.toLowerCase().split('-')[0];
    if (prefix === 'zh') return 'zh-CN';
    if (prefix === 'ja' || prefix === 'en') return prefix;
  }
  return 'en';
}
export function translator(locale) {
  return (key, values = {}) => (messages[locale]?.[key] ?? messages.en[key] ?? key)
    .replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? '—'));
}
export function applyLocale(locale, root = document) {
  const t = translator(locale);
  root.documentElement.lang = locale;
  for (const [attribute, target] of [['data-i18n', null], ['data-i18n-aria', 'aria-label'], ['data-i18n-placeholder', 'placeholder']]) {
    root.querySelectorAll(`[${attribute}]`).forEach(element => {
      const value = t(element.getAttribute(attribute));
      if (target) element.setAttribute(target, value); else element.textContent = value;
    });
  }
}
